#!/usr/bin/env node
// Smoke test against a running hub (default: wrangler dev --local on 127.0.0.1:8787). (c) CREATIVITY IS EVERYWHERE, LLC
//   node scripts/smoke.mjs --keys <keys.json from gen-keys> [--url http://127.0.0.1:8787] [--bot <bot_name>]
// Reads the key from the file and never prints it. Checks /health, 401 without a key, initialize, tools/list, propose_learning.
import fs from "node:fs";

const arg = (n, d) => { const i = process.argv.indexOf(n); return i > 0 ? process.argv[i + 1] : d; };
const base = arg("--url", "http://127.0.0.1:8787"), keysFile = arg("--keys"), botName = arg("--bot");
if (!keysFile) { console.error("usage: node scripts/smoke.mjs --keys <keys.json> [--url ...] [--bot name]"); process.exit(2); }
const entries = JSON.parse(fs.readFileSync(keysFile, "utf8")).keys;
const entry = botName ? entries.find(k => k.bot_name === botName) : entries.find(k => k.role === "bot") ?? entries[0];
const key = entry.key;
let id = 0, failed = 0;
const ok = (name, cond, detail = "") => { console.log(`${cond ? "PASS" : "FAIL"} ${name}${detail ? " — " + detail : ""}`); if (!cond) failed++; };
async function rpc(method, params = {}, auth = true) {
  const res = await fetch(base + "/mcp", { method: "POST", headers: { "content-type": "application/json", accept: "application/json, text/event-stream", "mcp-protocol-version": "2025-06-18",
    ...(auth ? { authorization: `Bearer ${key}` } : {}) }, body: JSON.stringify({ jsonrpc: "2.0", id: ++id, method, params }) });
  const t = await res.text();
  const msg = (res.headers.get("content-type") ?? "").includes("event-stream") ? t.split("\n").filter(l => l.startsWith("data:")).map(l => JSON.parse(l.slice(5))).find(m => m.result || m.error) : t ? JSON.parse(t) : null;
  return { status: res.status, msg };
}
const h = await fetch(base + "/health");
ok("GET /health", h.status === 200 && (await h.json()).ok === true);
const u = await rpc("tools/list", {}, false);
ok("POST /mcp without key → 401", u.status === 401);
const i = await rpc("initialize", { protocolVersion: "2025-06-18", capabilities: {}, clientInfo: { name: "smoke", version: "0" } });
ok("initialize", i.status === 200 && i.msg?.result?.serverInfo?.name === "blueprint-hub", `protocol ${i.msg?.result?.protocolVersion}`);
const tl = await rpc("tools/list");
const names = tl.msg?.result?.tools?.map(t => t.name) ?? [];
ok("tools/list", names.length >= 14 && names.includes("propose_learning"), `${names.length} tools (${entry.role})`);
const p = await rpc("tools/call", { name: "propose_learning", arguments: { category: "ethics",
  principle: { principle: "Show users which answers were generated by AI, at the point where they read them.", anti_pattern: "Presenting AI output as if a person wrote it.", why: "Users weigh AI output differently.", check: "Is every AI answer labelled where it is shown?" },
  claims: [{ claim: "Users asked for an AI label in support tickets." }], context: { stage: "launch", severity: "near_miss" } } });
const out = p.msg?.result && !p.msg.result.isError ? JSON.parse(p.msg.result.content[0].text) : null;
ok("propose_learning", out?.status === "pending_review", out ? `submission ${out.submission_id}, occurrence ${out.occurrence.count} on ${out.occurrence.target_id}, flags ${out.checks.flags.join(",") || "-"}` : JSON.stringify(p.msg).slice(0, 200));
const bad = await rpc("tools/call", { name: "propose_learning", arguments: { category: "ethics", text: "mail the fix to someone@example.com" } });
ok("propose_learning with an email → rejected", bad.msg?.result?.isError === true);
process.exit(failed ? 1 : 0);
